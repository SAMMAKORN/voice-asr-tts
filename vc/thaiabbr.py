"""อ่านตัวย่อภาษาไทยเป็นคำเต็มก่อนสังเคราะห์เสียง

`k2-fsa/OmniVoice` อ่านตัวย่อไม่ออกเหมือนที่อ่านตัวเลขอารบิกไม่ออก — "20 ส.ค. 2568"
ออกมาเป็นเสียงมั่วตรงกลางประโยค · โมเดลเขียนตัวย่อมาเองแม้ system prompt จะไม่ได้สั่ง
(ในบันทึกจริงเจอ ค.ศ., ส.ค., ปตท., น.) จึงต้องคลี่เป็นคำเต็มบนเส้นทางเสียง

เหมือน `vc/thainum.py` ทุกอย่าง: แปลงเฉพาะสายที่ไปเข้า TTS (`clean_for_tts`) ส่วน
หน้าจอ ประวัติสนทนาที่ส่งกลับให้โมเดล และ `transcript.md` ยังเป็นตัวย่อตามที่โมเดลเขียน

**ตารางนี้รับเฉพาะตัวย่อที่มีคำอ่านเดียว** ตัวย่อไทยจำนวนมากกำกวมจนเดาไม่ได้จากบริบท
โดยไม่ใช้โมเดลภาษา — "ม." เป็นได้ทั้งเมตร/หมู่/มัธยม/มหาวิทยาลัย, "อ." เป็นได้ทั้ง
อำเภอ/อาจารย์, "รร." เป็นได้ทั้งโรงเรียนและโรงแรม (นี่คือตัวอย่างในเอกสารของ
PyThaiNLP เอง ซึ่งต้องใช้ khamyo ที่เป็นโมเดล transformer มาเดาให้) เดาผิดแล้วผู้ใช้
ได้ยินคำที่ไม่ได้พูดถึงเลย แย่กว่าปล่อยให้อ่านตัวย่อผิด ๆ ถูก ๆ ตัวที่กำกวมจึงไม่อยู่ในตาราง

"ฯ" ที่เหลืออยู่ท้ายคำ (โปรดเกล้าฯ, สหประชาชาติฯ) ถูกตัดทิ้งเฉย ๆ เพราะมันคือ
"เครื่องหมายว่าตัดข้อความออก" ไม่ใช่เสียง — อ่านคำที่เหลือไปตรง ๆ ใกล้เคียงที่สุดแล้ว
"""
from __future__ import annotations

import re

MONTHS = {
    "ม.ค.": "มกราคม",
    "ก.พ.": "กุมภาพันธ์",
    "มี.ค.": "มีนาคม",
    "เม.ย.": "เมษายน",
    "พ.ค.": "พฤษภาคม",
    "มิ.ย.": "มิถุนายน",
    "ก.ค.": "กรกฎาคม",
    "ส.ค.": "สิงหาคม",
    "ก.ย.": "กันยายน",
    "ต.ค.": "ตุลาคม",
    "พ.ย.": "พฤศจิกายน",
    "ธ.ค.": "ธันวาคม",
}

ABBREVIATIONS: dict[str, str] = {
    **MONTHS,
    "พ.ศ.": "พุทธศักราช",
    "ค.ศ.": "คริสต์ศักราช",
    "กรุงเทพฯ": "กรุงเทพมหานคร",
    "ฯลฯ": "และอื่น ๆ",
    # หน่วยวัดที่ไม่มีคำอ่านอื่น
    "กม.": "กิโลเมตร",
    "กก.": "กิโลกรัม",
    "ซม.": "เซนติเมตร",
    "มม.": "มิลลิเมตร",
    "ตร.ม.": "ตารางเมตร",
    "ตร.ว.": "ตารางวา",
    "ลบ.ม.": "ลูกบาศก์เมตร",
    # ชื่อย่อที่คนไทยอ่านทีละพยางค์ — ใส่เท่าที่เจอในบันทึกจริงของการใช้งานนี้
    "ปตท.": "ปอตอทอ",
}

def _alternative(key: str) -> str:
    """รูปแบบที่ยอมรับของตัวย่อหนึ่งตัว

    ตัวย่อที่มีจุดคั่นอยู่ข้างใน ("ส.ค.", "พ.ศ.") ยอมให้จุดท้ายหายไปได้ เพราะโมเดล
    เขียน "20 ส.ค 2568" มาเป็นครั้งคราวและจุดข้างในก็ชี้ชัดพอแล้วว่าคือตัวย่อ
    ส่วนตัวย่อที่ไม่มีจุดข้างใน ("กก.", "กม.") บังคับให้ต้องมีจุดท้ายเสมอ ไม่งั้น
    "กก" ซึ่งเป็นคำไทยจริงจะกลายเป็น "กิโลกรัม"
    """
    body = re.escape(key)
    if key.endswith(".") and "." in key[:-1]:
        return body[:-len(re.escape("."))] + r"\.?"
    return body


# เรียงจากยาวไปสั้น ไม่งั้น "ตร.ม." จะถูก "ม." กินไปก่อน (ในตารางนี้ยังไม่มี "ม."
# เดี่ยว ๆ แต่กติกานี้ต้องถูกไว้ก่อน เผื่อมีคนเติมตัวย่อสั้นเข้ามาทีหลัง)
_PATTERN = re.compile(
    "|".join(_alternative(k) for k in sorted(ABBREVIATIONS, key=len, reverse=True)))
# "ฯ" ที่ไม่ได้อยู่ในตาราง — ตัดทิ้ง (ต้องรันหลังตาราง ไม่งั้น "ฯลฯ" จะโดนก่อน)
_LEFTOVER_PAISAN = re.compile(r"(?<=[ก-๛])ฯ")


def _expand(m: re.Match[str]) -> str:
    hit = m.group(0)
    # เติมจุดท้ายกลับให้ตรงกับ key เมื่อโมเดลเขียนตกไป (ดู `_alternative`)
    return ABBREVIATIONS.get(hit) or ABBREVIATIONS[hit + "."]


def speak_abbreviations(text: str) -> str:
    """แทนตัวย่อทุกตัวในข้อความด้วยคำอ่านเต็ม"""
    if not text:
        return text
    text = _PATTERN.sub(_expand, text)
    return _LEFTOVER_PAISAN.sub("", text)
