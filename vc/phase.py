"""สถานะของหนึ่งเทิร์นสนทนา (P2-5)

ก่อนหน้านี้ใช้ธง ``busy: bool`` ตัวเดียวคุมทั้ง "กำลังถอดเสียง" และ "กำลังพูด"
ทั้งสองอย่างจึงถูกมองเป็นเรื่องเดียวกัน พอผู้ใช้พูดต่ออีกประโยคระหว่างถอดเสียง
ระบบเห็น ``busy=True`` แล้วสั่งขัดจังหวะตัวเอง → ``cancel`` ถูก set ก่อนเข้า
``respond()`` → เทิร์นหายเงียบ ผู้ใช้ไม่ได้คำตอบและไม่เห็น error อะไรเลย

กติกาใหม่แยกตามช่วงของเทิร์น:

======================  ==============================================
phase                   เสียงพูดใหม่เข้ามาแล้วเกิดอะไร
======================  ==============================================
``IDLE``                เริ่มเทิร์นใหม่
``TRANSCRIBING``        **ไม่ขัด** — ต่อเป็นประโยคเดียวกันของเทิร์นเดิม
``GENERATING``          ขัด: ยกเลิกเทิร์นเดิม เริ่มเทิร์นใหม่
``SPEAKING``            ขัด: หยุดเสียงทันที ยกเลิกเทิร์นเดิม เริ่มใหม่
======================  ==============================================
"""
from __future__ import annotations

from enum import Enum


class TurnPhase(str, Enum):
    """ช่วงชีวิตของเทิร์น — ไล่ตามลำดับ IDLE → TRANSCRIBING → GENERATING → SPEAKING → IDLE

    สืบทอด ``str`` เพื่อให้ส่งขึ้นหน้าเว็บ/เขียนลง log ได้ตรง ๆ โดยไม่ต้องแปลงค่า
    """

    IDLE = "idle"
    TRANSCRIBING = "transcribing"
    GENERATING = "generating"
    SPEAKING = "speaking"

    def __str__(self) -> str:            # ให้ f-string อ่านง่ายใน log
        return self.value


# ช่วงที่ถือว่า "AI ถือไมค์อยู่" — เสียงของผู้ใช้ที่เข้ามาตอนนี้คือการพูดแทรกจริง
BARGE_IN_PHASES = frozenset({TurnPhase.GENERATING, TurnPhase.SPEAKING})


def interrupts(phase: TurnPhase) -> bool:
    """เสียงพูดที่เข้ามาในช่วงนี้ ควรตีความเป็นการพูดแทรกหรือไม่"""
    return phase in BARGE_IN_PHASES
